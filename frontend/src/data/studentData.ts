export const getSectionStats = (section: string) => {
  const sectionStudents = STUDENT_DATA.filter((s) => s.section === section);
  return {
    total: sectionStudents.length,
    avgLiteracy:
      sectionStudents.reduce((sum, s) => sum + s.literacy_percentage, 0) /
      sectionStudents.length,
    avgAttendance:
      sectionStudents.reduce((sum, s) => sum + s.attendance, 0) /
      sectionStudents.length,
    high: sectionStudents.filter((s) => s.literacy_level === "High").length,
    medium: sectionStudents.filter((s) => s.literacy_level === "Medium").length,
    low: sectionStudents.filter((s) => s.literacy_level === "Low").length,
  };
};

export const getTopPerformers = (limit: number = 10) => {
  return STUDENT_DATA.sort(
    (a, b) => b.literacy_percentage - a.literacy_percentage,
  ).slice(0, limit);
};

export const getLowPerformers = (limit: number = 10) => {
  return STUDENT_DATA.sort(
    (a, b) => a.literacy_percentage - b.literacy_percentage,
  ).slice(0, limit);
};
